# Đóng gói Optigo Print Agent:
# 1) Zip local (private/downloads) — tuỳ chọn
# 2) Bundle nhúng vào src/lib/printAgentPackage.generated.ts — BẮT BUỘC để Vercel tải được
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$repoRoot = Split-Path -Parent (Split-Path -Parent $root)
$distDir = Join-Path $root 'dist'
$privateDir = Join-Path $repoRoot 'private\downloads'
$zipName = 'OptigoPrintAgent.zip'
$stage = Join-Path $distDir 'stage'
$generatedTs = Join-Path $repoRoot 'src\lib\printAgentPackage.generated.ts'

$files = @(
  '1-Chay-agent.bat',
  '2-Cai-tu-dong-khoi-dong.bat',
  'print-agent.ps1',
  'HUONG-DAN.txt'
)

# --- Generate embedded TS (needed on Vercel) ---
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/** Auto-generated by pack:print-agent — do not edit by hand. */')
[void]$sb.AppendLine('export const PRINT_AGENT_PACKAGE_FILES: { name: string; contentBase64: string }[] = [')
foreach ($f in $files) {
  $src = Join-Path $root $f
  if (-not (Test-Path $src)) { throw "Thieu file: $src" }
  $bytes = [System.IO.File]::ReadAllBytes($src)
  $b64 = [Convert]::ToBase64String($bytes)
  [void]$sb.AppendLine('  {')
  [void]$sb.AppendLine("    name: '$f',")
  [void]$sb.AppendLine("    contentBase64: '$b64',")
  [void]$sb.AppendLine('  },')
}
[void]$sb.AppendLine('];')
[System.IO.File]::WriteAllText($generatedTs, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "OK: $generatedTs"

# --- Optional local zip ---
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Path $stage -Force | Out-Null
New-Item -ItemType Directory -Path $distDir -Force | Out-Null

foreach ($f in $files) {
  Copy-Item (Join-Path $root $f) (Join-Path $stage $f) -Force
}

$zipPath = Join-Path $distDir $zipName
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zipPath -Force

New-Item -ItemType Directory -Path $privateDir -Force | Out-Null
Copy-Item $zipPath (Join-Path $privateDir $zipName) -Force
Remove-Item $stage -Recurse -Force

Write-Host "OK: $zipPath"
Write-Host "OK: $(Join-Path $privateDir $zipName)"
Write-Host ""
Write-Host "Quan trong: commit file src/lib/printAgentPackage.generated.ts roi deploy."
